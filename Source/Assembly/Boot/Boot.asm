asm
bits 16
org 0x7C00

start:
    cli

    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7C00

    ; ====================================================
    ; REAL MODE CHECK
    ; ====================================================

    mov ax, 0xB800
    mov es, ax
    mov word [es:0], 0x0F52       ; R

    xor ax, ax
    mov ds, ax


    ; ====================================================
    ; ENABLE A20
    ; ====================================================

    in al, 0x92
    or al, 2
    out 0x92, al


    ; ====================================================
    ; LOAD GDT
    ; ====================================================

    lgdt [gdt_descriptor]


    ; ====================================================
    ; CLEAR PAGE TABLE AREA
    ;
    ; 9000 = PML4
    ; A000 = PDPT
    ; B000 = PAGE DIRECTORY
    ; ====================================================

    xor eax, eax
    mov edi, 0x9000
    mov ecx, 3072 / 4
    rep stosd


    ; ====================================================
    ; PML4 -> PDPT
    ; ====================================================

    mov dword [0x9000], 0xA003


    ; ====================================================
    ; PDPT -> PAGE DIRECTORY
    ; ====================================================

    mov dword [0xA000], 0xB003


    ; ====================================================
    ; PAGE DIRECTORY
    ;
    ; Identity map first 2 MiB
    ;
    ; Present  = bit 0
    ; Writable = bit 1
    ; PS       = bit 7
    ; ====================================================

    mov dword [0xB000], 0x00000083


    ; ====================================================
    ; LOAD CR3
    ; ====================================================

    mov eax, 0x9000
    mov cr3, eax


    ; ====================================================
    ; ENABLE PAE
    ; ====================================================

    mov eax, cr4
    or eax, (1 << 5)
    mov cr4, eax


    ; ====================================================
    ; ENABLE LONG MODE
    ; ====================================================

    mov ecx, 0xC0000080
    rdmsr

    or eax, (1 << 8)

    wrmsr


    ; ====================================================
    ; ENTER PROTECTED MODE
    ; ====================================================

    mov eax, cr0
    or eax, 1
    mov cr0, eax

    jmp 0x08:protected


; ========================================================
; 32-BIT PROTECTED MODE
; ========================================================

bits 32

protected:

    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax

    ; ====================================================
    ; PROTECTED MODE CHECK
    ; ====================================================

    mov dword [0xB8002], 0x0F500F50


    ; ====================================================
    ; ENABLE PAGING
    ; ====================================================

    mov eax, cr0
    or eax, (1 << 31)
    mov cr0, eax


    ; ====================================================
    ; ENTER 64-BIT LONG MODE
    ; ====================================================

    jmp 0x18:long_mode


; ========================================================
; 64-BIT LONG MODE
; ========================================================

bits 64

long_mode:

    mov ax, 0x10
    mov ds, ax
    mov es, ax
    mov ss, ax

    mov rsp, 0x7C00

    ; ====================================================
    ; LONG MODE CHECK
    ; ====================================================

    mov word [0xB8004], 0x0F4C       ; L


    ; ====================================================
    ; PRINT KAON
    ; ====================================================

    mov rdi, 0xB8000

    mov word [rdi + 10], 0x0F4B     ; K
    mov word [rdi + 12], 0x0F41     ; A
    mov word [rdi + 14], 0x0F4F     ; O
    mov word [rdi + 16], 0x0F4E     ; N


hang:
    cli
    hlt
    jmp hang


; ========================================================
; GDT
; ========================================================

bits 16

align 8

gdt:

    ; Null
    dq 0x0000000000000000

    ; 08h - 32-bit code
    dq 0x00CF9A000000FFFF

    ; 10h - data
    dq 0x00CF92000000FFFF

    ; 18h - 64-bit code
    dq 0x00AF9A000000FFFF

gdt_end:


; ========================================================
; GDT DESCRIPTOR
; ========================================================

gdt_descriptor:
    dw gdt_end - gdt - 1
    dd gdt


; ========================================================
; PAD TO 512 BYTES
; ========================================================

times 510 - ($ - $$) db 0

dw 0xAA55
